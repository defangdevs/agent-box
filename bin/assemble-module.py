#!/usr/bin/env python3
"""Assemble modules/agent-box.nix from modules/agent-box.nix.in + modules/src/*.

Why this exists
---------------
Deployed boxes fetch EXACTLY ONE file — aws/template.yaml's user-data and
agent-box-update.service both `builtins.fetchurl .../modules/agent-box.nix` and
pin a single sha256 (issue #51). raw.githubusercontent is dual-stack (IPv6-only
boxes reach it via NAT64) and needs no unpack step on a journal-only first boot.
That constraint is on the *fetched artifact*, not on how we author it.

So we keep the source split into real, tool-visible assets (a .py the linters
can see, later .js/.css) and mechanically re-embed them into the one committed
file at build time. `modules/agent-box.nix` is GENERATED; edit the `.in`
template and `modules/src/`, then rerun this script (or `nix run .#assemble`).

Include mechanism
-----------------
A line matching `<indent>@@include:<relpath>@@` (relative to the including
file's directory) is replaced by the target file's contents:
  * nested includes in the target are resolved first;
  * the target is escaped for the STRING SYNTAX of the including file — Nix
    indented-string escaping when the host is a `.nix`/`.in` file, Python
    triple-quote-string escaping when it is a `.py`, none otherwise. Both
    dialects are no-op for a payload that contains nothing special, which is
    why the assets predating either escaper did not move when it landed;
  * every non-blank line is re-indented to the marker's own indentation
    (blank lines stay empty), so a dedented, col-0 source file (real Python the
    linters accept) round-trips back to its indented in-string form byte-exact.

`@@include-verbatim:<relpath>@@` splices the target WITHOUT escaping (still
re-indented). It exists for payloads that still contain live Nix antiquotes:
the src file holds the body exactly as it sat inside the template's indented
string — Nix-string dialect, `''$`-escapes and all — so de-inlining is a pure,
byte-identical move (issue #154 Phase 1). As Phase 2 turns each payload into a
real script (antiquotes gone, dialect unescaped), its marker flips to the
escaping `@@include:` form above.
"""
import argparse
import difflib
import re
import sys
from pathlib import Path

MARKER = re.compile(
    r"^(?P<indent>[ ]*)@@include(?P<verbatim>-verbatim)?:(?P<path>.+)@@[ ]*$"
)

BANNER = """\
# @@GENERATED@@ — DO NOT EDIT THIS FILE BY HAND.
# Source of truth: modules/agent-box.nix.in + modules/src/*. Regenerate with
#   nix run .#assemble        (or: python3 bin/assemble-module.py)
# CI (`module-generated-up-to-date`) fails if this file is stale.
"""


# A run of apostrophes, optionally glued to the `${` that follows it. Matching
# the two together is what makes the escaping correct: how a quote run has to
# be escaped depends on whether a `${` escape lands right behind it (#244).
QUOTE_RUN_OR_ANTIQUOTE = re.compile(r"'+\$\{|'+|\$\{")


def nix_escape(text: str) -> str:
    r"""Escape a literal for embedding inside a Nix '' indented string.

    Only `''` and `${` are special there (backslashes are literal), so the
    escaping is two rules: a literal `''` is written `'''`, and a literal
    `${` is written `''${`.

    They cannot be applied as two independent passes, because Nix lexes a run
    of apostrophes greedily, three at a time, and *both* `'''` and the `''${`
    we emit start with `''`. So an apostrophe is only safe unescaped when the
    lexer cannot glue it onto whatever follows. Two places where it can:

      * directly before a `${` — an ordinary shell line like
        `echo "key '${KEY}'"`. `'` + `''${` reads as an escaped `''` plus a
        LIVE antiquotation: a build failure at best (`undefined variable`
        pointing into the generated module), a silently mangled payload at
        worst.
      * at the very end, where the host's closing `''` follows: `'` + `''`
        reads as an escaped `''` and the string never closes.

    Both are fixed by escaping that apostrophe too, as `''\'`, which leaves the
    `''` behind it unambiguous. That also makes the result self-contained: it
    can be spliced anywhere inside an indented string, hard against the
    closing delimiter included (issue #244)."""

    def escape(match: re.Match) -> str:
        token = match.group(0)
        antiquote = token.endswith("${")
        quotes = len(token) - 2 if antiquote else len(token)
        pairs, odd = divmod(quotes, 2)
        out = "'''" * pairs
        if odd:
            unsafe = antiquote or match.end() == len(text)
            out += "''\\'" if unsafe else "'"
        return out + ("''${" if antiquote else "")

    return QUOTE_RUN_OR_ANTIQUOTE.sub(escape, text)


# Any run of double quotes. Whether it needs escaping depends on its length
# AND on what follows it, the same way a Nix apostrophe run does — so the run
# is matched whole and judged in one place.
DOUBLE_QUOTE_RUN = re.compile(r'"+')


def python_escape(text: str) -> str:
    r"""Escape a literal for embedding inside a Python triple-quoted string.

    The three assets that predate this escaper (settings.js, settings.css,
    potato.svg) carry no backslash and no quote run, so they round-trip
    through it byte-identically — deliberately, because the generated module
    must not move when the escaper is introduced. A VENDORED asset is what
    makes it necessary: minified JavaScript carries regex escapes (`/[\s\S]/`
    in idiomorph), and inside a non-raw triple-quoted host Python eats it.

    Two rules, applied in this order:

      * `\` becomes `\\`. Python leaves an UNRECOGNIZED escape (`\s`, `\S`,
        `\/`) alone today, so an unescaped payload can look fine while
        emitting a SyntaxWarning per occurrence — and that warning is slated
        to become a SyntaxError. The RECOGNIZED ones need no future Python to
        bite: `\n` inside a JavaScript regex literal (`/[\n]/`) lands in the
        source as an actual newline, which is a syntax error there, and a bad
        `\x` fails the parse outright. None of it is visible to the
        up-to-date CI check, which regenerates with this same assembler and
        so agrees with itself — issue #244's lesson, on the other dialect.

      * a run of `"` is escaped quote by quote when it could reach the host's
        closing delimiter: 3 or more anywhere, or ANY run at the very end,
        where the closing delimiter follows it directly. A run of one or two
        mid-payload is legal inside a triple-quoted string and is left alone,
        which is the whole reason the pre-existing assets do not move.
        Escaping the trailing case too makes the result splice-able anywhere,
        hard against the delimiter included — the same property nix_escape
        gives its own output (issue #244)."""
    text = text.replace("\\", "\\\\")

    def escape(match: re.Match) -> str:
        run = match.group(0)
        unsafe = len(run) >= 3 or match.end() == len(text)
        return ('\\"' * len(run)) if unsafe else run

    return DOUBLE_QUOTE_RUN.sub(escape, text)


def escaper_for(path: Path):
    if path.suffix in (".nix", ".in"):
        return nix_escape
    if path.suffix == ".py":
        return python_escape
    return lambda s: s


def reindent(text: str, indent: str) -> str:
    return "\n".join(indent + line if line else line for line in text.split("\n"))


def resolve(path: Path) -> str:
    """Return `path` with all its @@include@@ markers expanded.

    Children are escaped for THIS file's string syntax and re-indented to the
    marker column; `path`'s own bytes are returned as-is."""
    escape = escaper_for(path)
    out = []
    for line in path.read_text().split("\n"):
        m = MARKER.match(line)
        if not m:
            out.append(line)
            continue
        child = (path.parent / m.group("path")).resolve()
        if not child.exists():
            sys.exit(f"assemble-module: {path}: missing include target {child}")
        payload = resolve(child)
        # A source file's conventional terminal newline is not part of the
        # in-string payload — drop exactly one so the marker line is replaced
        # in place rather than gaining a trailing blank line.
        if payload.endswith("\n"):
            payload = payload[:-1]
        # -verbatim: the payload is already in the host's string dialect;
        # splice it untouched.
        if not m.group("verbatim"):
            payload = escape(payload)
        out.append(reindent(payload, m.group("indent")))
    return "\n".join(out)


def assemble(repo: Path) -> str:
    template = repo / "modules" / "agent-box.nix.in"
    return BANNER + resolve(template)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero (with a diff) if the committed file is stale",
    )
    ap.add_argument(
        "--repo",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="repo root (default: parent of bin/)",
    )
    ap.add_argument(
        "--resolve",
        type=Path,
        metavar="FILE",
        help="expand FILE's @@include@@ markers and print the result, "
             "instead of assembling the module. For a consumer that needs "
             "a modules/src asset as a finished file rather than embedded "
             "in the Nix module — the native runtime profile builds the "
             "settings daemon this way (issue #154 Phase 4).",
    )
    args = ap.parse_args()
    if args.resolve:
        # Same resolve() the module assembly uses, so the two backends
        # cannot disagree about what a marker means. A .py host escapes its
        # children for a Python string exactly as the module assembly does,
        # so the daemon the native profile builds this way is byte-identical
        # to the one embedded in the module.
        sys.stdout.write(resolve(args.resolve.resolve()))
        return 0
    out_path = args.repo / "modules" / "agent-box.nix"
    generated = assemble(args.repo)
    if args.check:
        current = out_path.read_text() if out_path.exists() else ""
        if current != generated:
            diff = difflib.unified_diff(
                current.splitlines(keepends=True),
                generated.splitlines(keepends=True),
                fromfile="modules/agent-box.nix (committed)",
                tofile="modules/agent-box.nix (regenerated)",
            )
            sys.stderr.writelines(diff)
            sys.stderr.write(
                "\nmodules/agent-box.nix is stale — run `nix run .#assemble`.\n"
            )
            return 1
        print("modules/agent-box.nix is up to date")
        return 0
    out_path.write_text(generated)
    print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
